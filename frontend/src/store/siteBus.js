/*
  这个文件是网站模块的「消息小喇叭」（bus = 总线）——通知站点列表该刷新了。

  业务背景：面板管理的是 Nginx/OpenResty 站点。「网站列表」在一个窗口里，
  而编辑某个站点（改域名、根目录、SSL、伪静态等）会打开另一个独立桌面窗口。
  站点配置改完后真正落地的是后端的 Nginx 配置文件，列表窗口自己不会知道。

  于是这里只放一个版本号当信号：站点编辑窗口保存成功就把它 +1，
  列表窗口 watch 到变化后重新请求 /api/sites，让列表里的域名、状态、
  证书信息立刻和刚保存的结果对齐，而不用用户手动点刷新。

  用法：站点编辑窗口保存成功后调 bumpSites()；列表窗口 watch(siteRevision, ...) 重新 load()。
*/
import { ref } from 'vue'                     // 用 ref 包一个数字，才能被列表窗口 watch 到变化

// 站点数据版本号：独立「站点编辑」窗口保存成功后将版本号 +1，
// 「网站」列表窗口监听到变化即重新 load()，从而与独立窗口保持同步。
// --- 对外暴露：站点数据的版本号（只表示「站点配置动过了」这件事） ---
export const siteRevision = ref(0)

// --- 通知全站：站点配置已保存，请重新拉取网站列表 ---
export function bumpSites() {
  siteRevision.value += 1                    // 递增而非布尔取反，连续保存多个站点也不会互相抵消掉通知
}