/*
  这个文件是「数据库连接列表该刷新了」的一声招呼——一个跨窗口的变更通知铃。

  业务背景：面板里管理 MySQL/MariaDB/Redis 连接时，「连接列表」在数据库主窗口，
  而「新增/编辑连接」是另一个独立的桌面窗口。两个窗口在组件树上互不相干，
  子窗口保存完连接后没法直接喊主窗口「你的列表过期了」。

  于是用一个只有数字的共享状态当信号：谁改动了数据库连接就把它 +1，
  主窗口 watch 到数字变了就重新请求 /api/databases 拉一遍列表。
  这里刻意不缓存连接数据本身——只传「变了」这个事实，真实数据仍以后端为准，
  避免两个窗口各存一份互相不一致（连接里含密码等敏感信息，更不该在前端多存）。

  用法：数据库表单窗口保存/删除成功后调 notifyDatabasesChanged()；
  主窗口 watch(dbVersion, ...) 后重新 load()。
*/
import { ref } from 'vue'                          // 用 ref 包一个数字，才能被主窗口 watch 到变化

// 共享信号：数据库连接新增/修改/删除后自增版本号，
// 供数据库主窗口（DatabaseWindow.vue）watch 到后自动刷新连接列表。
// 由于添加/编辑连接已改到独立窗口，主窗口需要感知跨窗口的数据变化。
// --- 对外暴露：数据库连接的变更版本号（只是计数，不含任何连接明细） ---
export const dbVersion = ref(0)

// --- 通知全站：数据库连接已被改动，请重新拉取列表 ---
export function notifyDatabasesChanged() {
  dbVersion.value += 1                             // 只需「值变了」即可触发 watch，用递增而非取反，多次连续改动也不会自相抵消
}
